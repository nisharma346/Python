# what is python?
# Python is a high-level, interpreted, general-purpose programming language used to
# develop software, websites, applications, automation scripts, AI systems, and much more.

# Python was created by Guido van Rossum and was first released in 1991.

# why python is called a high level language?
# Python is called a high-level programming language because its syntax is easy for humans
#  to read and understand and it hides most of the complex details of the computer's hardware.

# Five Main Features of Python

# 1.Simple and Easy to Learn
# Python has a simple syntax that is easy for beginners to understand and write.

# 2.Language
# Python code is executed by an interpreter, so it does not need to be compiled separately before execution.

# 3.Object-Oriented
# Python supports object-oriented programming concepts such as classes, objects, inheritance, and polymorphism.

# 4.Portable
# Python programs can run on different operating systems such as Windows, Linux, and macOS with little or no modification.

# 5.Large Standard Library
# Python provides many built-in modules and libraries for tasks such as file handling, mathematics, networking, web development, and data processing.

# why python is called an interpreted language?
# Python is called an interpreted language because Python programs are executed by an interpreter, rather than being directly converted into machine 
# code by the programmer before execution.

# Applications of Python 🐍
# 1. Web Development 🌐
# Python is used to create websites and web applications using frameworks such as Django and Flask.
# Example: E-learning websites, shopping websites, banking applications.

# 2. Artificial Intelligence & Machine Learning 🤖
# Python is widely used for AI and Machine Learning because of libraries such as NumPy, Pandas, TensorFlow, and Scikit-learn.
# Example: Chatbots, recommendation systems, image recognition.

# 3. Data Science & Data Analysis 📊
# Python is used to collect, process, analyze, and visualize large amounts of data.
# Example: Business reports, data visualization, prediction.

# 4. Automation ⚙️
# Python can automate repetitive tasks.
# Example: Sending emails, managing files, generating reports, web automation.

# 5. Game Development 🎮
# Python can be used to develop simple games using libraries such as Pygame.

# 6. Desktop Applications 🖥️
# Python can be used to create desktop GUI applications using Tkinter, PyQt, etc.

# 7. Scientific Computing 🔬
# Python is used in scientific and mathematical applications for calculations, simulations, and research.

# 8. Cybersecurity 🔐
# Python is used for security testing, network analysis, and developing cybersecurity tools.

