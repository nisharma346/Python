# what is python?
# Python is a high-level, interpreted, general-purpose programming language used to
# develop software, websites, applications, automation scripts, AI systems, and much more.

# Python was created by Guido van Rossum and was first released in 1991.

# why python is called a high level language?
# Python is called a high-level programming language because its syntax is easy for humans to read and understand and it hides most of the complex details of the computer's hardware.